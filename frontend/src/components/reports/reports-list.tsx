"use client";

import { useEffect, useState } from "react";
import Link from "next/link";

import { SeverityBadge } from "@/components/incidents/severity-badge";
import { StatusBadge } from "@/components/incidents/status-badge";
import { ReportDownloadButton } from "@/components/reports/report-download-button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Skeleton } from "@/components/ui/skeleton";
import { listIncidentsApi } from "@/lib/api";
import { analystErrorMessage } from "@/lib/analyst-errors";
import { formatUtc } from "@/lib/format";
import type { PersistedIncident } from "@/lib/types";

export function ReportsList() {
  const [incidents, setIncidents] = useState<PersistedIncident[] | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    const controller = new AbortController();
    listIncidentsApi(controller.signal)
      .then((rows) => {
        setIncidents(rows);
      })
      .catch((caught: unknown) => {
        if (caught instanceof DOMException && caught.name === "AbortError") {
          return;
        }
        setError(analystErrorMessage(caught));
        setIncidents([]);
      });
    return () => controller.abort();
  }, []);

  if (incidents === null && !error) {
    return (
      <div className="grid gap-4" aria-busy="true" aria-label="Loading incidents for reports">
        <Skeleton className="h-32" />
        <Skeleton className="h-32" />
      </div>
    );
  }

  if (error) {
    return (
      <p className="text-sm text-destructive" role="alert">
        {error}
      </p>
    );
  }

  if (!incidents || incidents.length === 0) {
    return (
      <p className="text-sm text-muted-foreground">
        No persisted incidents are available to report on.
      </p>
    );
  }

  return (
    <div className="grid gap-4">
      {incidents.map((incident) => (
        <Card key={incident.id}>
          <CardHeader className="flex flex-row items-start justify-between gap-3">
            <div>
              <CardTitle>{incident.title}</CardTitle>
              <CardDescription>
                Created {formatUtc(incident.createdAt)} · HTML generated by the backend
              </CardDescription>
            </div>
            <div className="flex flex-wrap gap-2">
              <SeverityBadge severity={incident.severity} />
              <StatusBadge status={incident.status} />
            </div>
          </CardHeader>
          <CardContent className="flex flex-wrap items-start gap-3">
            <Link
              href={`/incidents/${incident.id}`}
              className="text-sm text-primary hover:underline"
            >
              Open incident
            </Link>
            <ReportDownloadButton incidentId={incident.id} />
          </CardContent>
        </Card>
      ))}
    </div>
  );
}
